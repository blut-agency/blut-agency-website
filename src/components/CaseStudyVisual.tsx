/** `useVisual` flags -> the visual-<n>-size variant the live site renders. */
export function visualVariant(useVisual: boolean[]): Variant {
  const i = useVisual.findIndex(Boolean);
  const n = (i < 0 ? 0 : i) + 1;
  return (n in SHAPES ? n : 1) as Variant;
}

export default function CaseStudyVisual({
  slug,
  variant,
  speed,
  startOnPlay = false,
  auto = true,
  playerSlug = "",
  visualizationJson,
}: {
  slug: string;
  variant: Variant;
  speed: number;
  /** True for the shapes beside an audio player: they follow the track instead of looping. */
  startOnPlay?: boolean;
  /** False when the shape should stay still until playback starts. */
  auto?: boolean;
  /** `data-player-file` slug of the Vimeo player to follow, when startOnPlay is set. */
  playerSlug?: string;
  /**
   * Per-track amplitude samples. embeds.js scales the shapes frame by frame from
   * this, which is what makes them pulse; without it only the slow morph runs.
   * One textarea per form slug is enough for the whole document.
   */
  visualizationJson?: string;
}) {
  const shape = SHAPES[variant];
  const sizeClass = `visual-${variant}-size`;

  return (
    <div
      data-visual-start-on-play={String(startOnPlay)}
      data-visual-form={slug}
      data-visual-speed={String(speed)}
      data-visual-auto={String(auto)}
      data-visual-player={playerSlug}
      className="visual-canvas"
    >
      {shape.svgs.map((svg, i) => {
        // 0 = base shape, 1 = the thin overlay line, 2 = the morph target
        const formClass =
          i === 0 ? "form" : i === 1 ? "form is-thin-line" : "form is-end-scene";
        const sound = shape.sounds[i];
        return (
          <div className={sizeClass} key={i}>
            <div {...(sound ? { "data-visual-sound": sound } : {})} className={formClass}>
              <svg
                xmlns="http://www.w3.org/2000/svg"
                width="100%"
                viewBox={svg.viewBox}
                fill={svg.fill}
                data-visual-path={svg.role}
                className="visual-svg"
              >
                <path d={svg.d} stroke="currentColor" className={svg.pathClass} />
              </svg>
            </div>
          </div>
        );
      })}
      <div className="visual-background-noise" />
      {visualizationJson && (
        <textarea
          data-visual-json={slug}
          data-visual-player={slug}
          className="visualization-json"
          defaultValue={visualizationJson}
        />
      )}
    </div>
  );
}
